import {build} from 'esbuild';
import {mkdir, cp, copyFile, readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {basename} from 'node:path';
await mkdir('dist/vendor', {recursive: true});
await cp('public', 'dist', {recursive: true});
const common = {outdir: 'dist', bundle: true, format: 'esm', platform: 'browser', target: ['safari16.4', 'chrome110'], minify: true, metafile: true, entryNames: '[name]-[hash]'};
const workerBuild = await build({...common, entryPoints: {worker: 'src/worker.mjs'}});
const workerName = basename(Object.keys(workerBuild.metafile.outputs).find(path => path.endsWith('.js')));
const appBuild = await build({...common, entryPoints: {app: 'src/app.mjs'}, define: {__WORKER_URL__: JSON.stringify('/' + workerName)}});
const appName = basename(Object.keys(appBuild.metafile.outputs).find(path => path.endsWith('.js')));
const css = await readFile('public/style.css');
const cssName = 'style-' + createHash('sha256').update(css).digest('hex').slice(0, 12) + '.css';
await writeFile('dist/' + cssName, css);
const html = (await readFile('public/index.html', 'utf8')).replace('src="/app.js"', 'src="/' + appName + '"').replace('href="/style.css"', 'href="/' + cssName + '"').replace('href="/manifest.webmanifest"', 'href="/manifest-quality.webmanifest"');
await writeFile('dist/index.html', html);
await writeFile('dist/quality.html', html);
await writeFile('dist/recording.html', html);
const manifest = JSON.parse(await readFile('public/manifest.webmanifest', 'utf8'));
manifest.start_url = '/recording.html';
for (const name of ['manifest.webmanifest', 'manifest-quality.webmanifest']) await writeFile('dist/' + name, JSON.stringify(manifest));
const vendor = ['ort-wasm-simd-threaded.jsep.mjs', 'ort-wasm-simd-threaded.jsep.wasm'];
for (const file of vendor) await copyFile('node_modules/onnxruntime-web/dist/' + file, 'dist/vendor/' + file);
const licenses = ['@huggingface/transformers/LICENSE', 'opencc-js/LICENSE'];
let notices = 'Voice2Txt 獨立版使用 Transformers.js (Apache-2.0)、ONNX Runtime (MIT)、OpenCC (MIT)。Whisper 模型來自 OpenAI Whisper (MIT)，ONNX 轉換來源為 onnx-community。\n\n';
for (const file of licenses) notices += '\n--- ' + file + ' ---\n' + await readFile('node_modules/' + file, 'utf8');
for (const name of ['onnxruntime', 'whisper']) notices += '\n--- ' + name + ' ---\n' + await readFile('public/' + name + '-LICENSE.txt', 'utf8');
await writeFile('dist/LICENSES.txt', notices);
const assets = ['/', '/index.html', '/quality.html', '/recording.html', '/' + appName, '/' + workerName, '/' + cssName, '/manifest.webmanifest', '/manifest-quality.webmanifest', '/icon.png', '/LICENSES.txt', ...vendor.map(f => '/vendor/' + f)];
const hash = createHash('sha256');
for (const asset of assets) hash.update(await readFile('dist/' + (asset === '/' ? 'index.html' : asset.slice(1))));
const version = hash.digest('hex').slice(0, 12);
await writeFile('dist/sw.js', `const CACHE='voice2txt-shell-${version}';
const ASSETS=${JSON.stringify(assets)};
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS.map(path=>new Request(path,{cache:'reload'})))).then(()=>self.skipWaiting())));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('voice2txt-shell-')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{if(event.request.method!=='GET'||new URL(event.request.url).origin!==self.location.origin)return;if(event.request.mode==='navigate'){event.respondWith(fetch(event.request).catch(()=>caches.open(CACHE).then(async cache=>(await cache.match(event.request,{ignoreSearch:true}))||cache.match('/index.html'))));return;}event.respondWith(caches.open(CACHE).then(async cache=>(await cache.match(event.request,{ignoreSearch:true}))||fetch(event.request)));});
`);
console.log('已建立獨立 PWA，版本 ' + version);
